#!/usr/bin/env python3
"""The OB-12's DSP programs as straight line code for tms57070.cpp's translated path.
usage: gen_fast.py rom/dsp build/tms_fast.inc

Reads the distinct prog*.pmem.bin and their headers (carved by ob12_carve.py). The programs have no
jump, call or repeat, so each half frame (words 000-0FF, 100-1FF) becomes one function of 256
constant words. For each half the CR1 mode bits at its first word are worked out by following the
words that set them around the loop; Core::fast_ready() checks them before a half is entered, so a
wrong guess here costs speed, never correctness. The output holds firmware words: it goes to
build/, outside git."""
import glob
import struct
import sys

src, out = sys.argv[1], sys.argv[2]

# CR1 fields a step's work depends on: (shift, width)
MASM, MOSM, MRDM, AOVM, MOVM, EXTMEM, EXT, LDMEM, LCMEM = (14, 2), (12, 2), (9, 3), (8, 1), (16, 1), (19, 1), (20, 1), (21, 1), (23, 1)
FIELDS = [MASM, MOSM, MRDM, AOVM, MOVM, EXTMEM, EXT, LDMEM, LCMEM]


def modes_after(word, known):
    """known: {field: value or None}. Follows tms57070.cpp's secondary() and the CR1 loads."""
    top = word >> 24
    if top == 0xCD:  # CR1 = the word
        return {f: (word >> f[0]) & ((1 << f[1]) - 1) for f in FIELDS}
    if top >= 0x80:  # dual words and the other C0+ words have no secondary
        return known
    op, args = (word >> 16) & 0x3F, (word >> 14) & 3
    flag4, flag8 = (word >> 14) & 1, (word >> 15) & 1
    k = dict(known)
    if op == 0x28: k[MASM] = args
    elif op == 0x29: k[MOSM] = args
    elif op == 0x2A: k[MRDM] = args
    elif op == 0x2B: k[MRDM] = args + 4
    elif op == 0x2D: k[MOVM if flag8 else AOVM] = flag4
    elif op == 0x2E: k[LCMEM if flag8 else LDMEM] = flag4
    elif op == 0x22 and args == 1: k = {f: None for f in FIELDS}  # CR1 from CMEM
    return k


programs = []
for path in sorted(glob.glob(src + "/prog*.pmem.bin")):
    data = open(path, "rb").read()
    if len(data) != 2048:
        continue
    words = struct.unpack(">512I", data)
    if any(w >> 24 >= 0xE0 for w in words):
        print("skipped, has a jump or repeat:", path)
        continue
    header = open(path.replace(".pmem.bin", ".hdr.bin"), "rb").read()
    cr1 = header[3] << 16 | header[4] << 8 | header[5]
    if all(p[0] != words for p in programs):
        programs.append((words, cr1))
if len(programs) > 3:
    sys.exit("more than 3 programs: add fast_ members to tms57070.h")

lines = ["// Generated by tools/gen_fast.py. Firmware words: do not commit.", ""]
lines.append("static const uint32_t fast_words[%d][512] = {" % len(programs))
for words, _ in programs:
    lines.append("    {" + ", ".join("0x%08X" % w for w in words) + "},")
lines.append("};")
expect = []
for n, (words, cr1) in enumerate(programs):
    known = {f: (cr1 >> f[0]) & ((1 << f[1]) - 1) for f in FIELDS}
    at = {}
    for lap in range(3):  # around the loop until the state at the two entries has settled
        for pc, w in enumerate(words):
            if pc in (0, 256):
                at[pc] = dict(known) if lap == 0 or pc not in at else {f: (v if at[pc][f] == v else None) for f, v in known.items()}
            known = modes_after(w, known)
    pair = []
    for half, pc in enumerate((0, 256)):
        mask = value = 0
        for f, v in at[pc].items():
            if v is not None:
                mask |= ((1 << f[1]) - 1) << f[0]
                value |= v << f[0]
        pair.append((mask, value))
        lines.append("void Core::fast_%d%s() {" % (n, "ab"[half]))
        lines.append("    FAST_ENTER(0x%06Xu, 0x%06Xu)" % (mask, value))
        for i in range(pc, pc + 256, 8):
            lines.append("    " + " ".join("W(0x%08Xu)" % w for w in words[i:i + 8]))
        lines.append("    FAST_LEAVE")
        lines.append("}")
    expect.append(pair)
for n in range(len(programs), 3):
    lines.append("void Core::fast_%da() {} void Core::fast_%db() {}" % (n, n))
lines.append("const Core::FastHalf Core::fast_table[][2] = {" + ", ".join("{&Core::fast_%da, &Core::fast_%db}" % (n, n) for n in range(3)) + "};")
lines.append("static const uint32_t fast_expect[%d][2][2] = {" % len(programs) + ", ".join(
    "{{0x%06Xu, 0x%06Xu}, {0x%06Xu, 0x%06Xu}}" % (p[0][0], p[0][1], p[1][0], p[1][1]) for p in expect) + "};")
lines.append("void Core::select_fast() {")
lines.append("    fast_program = -1;")
lines.append("    if (!engine_options(options)) return;")
lines.append("    for (int n = 0; n < %d; n++) {" % len(programs))
lines.append("        bool same = true;")
lines.append("        for (int i = 0; i < 512 && same; i++) same = pmem[i] == fast_words[n][i];")
lines.append("        if (!same) continue;")
lines.append("        fast_program = n;")
lines.append("        for (int half = 0; half < 2; half++) { fast_mask[half] = fast_expect[n][half][0]; fast_value[half] = fast_expect[n][half][1]; }")
lines.append("        return;")
lines.append("    }")
lines.append("}")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("%d programs -> %s; CR1 mask, value per half:" % (len(programs), out), " ".join("%06X,%06X %06X,%06X" % (p[0][0], p[0][1], p[1][0], p[1][1]) for p in expect))
